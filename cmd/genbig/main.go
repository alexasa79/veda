package main

import (
    "bufio"
    "flag"
    "fmt"
    "math/rand"
    "os"
    "time"
)

func main() {
    var (
        lines = flag.Int("lines", 100000, "number of payload lines to generate (payload lines)")
        out   = flag.String("out", "", "output Go file path (default: stdout)")
        pkg   = flag.String("pkg", "main", "package name for generated file")
        mode  = flag.String("mode", "comments", "payload mode: comments|funcs|consts|vars|rich")
        name  = flag.String("name", "bigprog", "label used in comments/identifiers")
        seed  = flag.Int64("seed", 0, "PRNG seed (0 = time-based)")
    )
    flag.Parse()

    var (
        f  *os.File
        bw *bufio.Writer
    )
    if *out != "" {
        var err error
        f, err = os.Create(*out)
        if err != nil {
            fmt.Fprintf(os.Stderr, "failed to create %s: %v\n", *out, err)
            os.Exit(1)
        }
        defer f.Close()
        bw = bufio.NewWriterSize(f, 1<<20) // 1 MiB buffer
    } else {
        bw = bufio.NewWriterSize(os.Stdout, 1<<20)
    }
    defer bw.Flush()

    // Seed RNG for randomized modes
    if *seed == 0 {
        *seed = time.Now().UnixNano()
    }
    rnd := rand.New(rand.NewSource(*seed))

    // Header
    fmt.Fprintf(bw, "package %s\n\n", *pkg)
    fmt.Fprintln(bw, "import \"fmt\"")
    fmt.Fprintln(bw)
    fmt.Fprintln(bw, "// Code generated by cmd/genbig; DO NOT EDIT.")
    fmt.Fprintf(bw, "// Payload: %d lines, mode=%s, name=%s\n\n", *lines, *mode, *name)

    // Main ensures the file compiles and the import is used.
    fmt.Fprintln(bw, "func main() {")
    fmt.Fprintf(bw, "\tfmt.Println(\"generated %s (%d lines, mode=%s)\")\n", *name, *lines, *mode)
    fmt.Fprintln(bw, "}")
    fmt.Fprintln(bw)

    switch *mode {
    case "comments":
        // Emit many comment lines (valid, lightweight to compile)
        for i := 1; i <= *lines; i++ {
            fmt.Fprintf(bw, "// %s payload line %d\n", *name, i)
        }

    case "funcs":
        // Emit many tiny functions (heavier to compile, but syntactically rich)
        for i := 1; i <= *lines; i++ {
            // single-line function to match requested line count
            fmt.Fprintf(bw, "func %s_f%d() int { return %d }\n", *name, i, i)
        }

    case "consts":
        // Emit many top-level constants
        for i := 1; i <= *lines; i++ {
            fmt.Fprintf(bw, "const %s_C%d = %d\n", *name, i, i)
        }

    case "vars":
        // Emit many top-level variables (unused is fine at package scope if referenced by blank identifier)
        // We create distinct names and assign simple literals.
        for i := 1; i <= *lines; i++ {
            fmt.Fprintf(bw, "var %s_V%d = %d\n", *name, i, i)
        }
        // Reference a few to silence potential linters (compiler doesn't require this)
        fmt.Fprintln(bw)
        fmt.Fprintln(bw, "func init() {")
        for i := 1; i <= 5 && i <= *lines; i++ {
            fmt.Fprintf(bw, "\t_ = %s_V%d\n", *name, i)
        }
        fmt.Fprintln(bw, "}")

    case "rich":
        // Generate randomized, multi-line functions until we reach the target payload lines
        linesWritten := 0
        fnIdx := 1

        write := func(format string, args ...interface{}) {
            fmt.Fprintf(bw, format, args...)
            // Count newlines in format to approximate line count
            s := fmt.Sprintf(format, args...)
            for i := 0; i < len(s); i++ {
                if s[i] == '\n' {
                    linesWritten++
                }
            }
        }

        for linesWritten < *lines {
            // Randomize function footprint sizes
            loops := 1 + rnd.Intn(3)      // 1..3 top-level loops
            ifs := 1 + rnd.Intn(3)        // 1..3 if blocks
            switches := rnd.Intn(2)       // 0..1 switches
            extra := rnd.Intn(3)          // 0..2 extra blocks

            write("func %s_rich_%d(n int) int {\n", *name, fnIdx)
            write("\tacc := 0\n")
            write("\tj := 0\n")

            // Emit loops: classic for and while-style
            for li := 0; li < loops; li++ {
                if rnd.Intn(2) == 0 {
                    // for i := 0; i < k; i++
                    k := 3 + rnd.Intn(7)
                    write("\tfor i := 0; i < %d; i++ {\n", k)
                    write("\t\tacc += (i + n) %% %d\n", 7+rnd.Intn(9))
                    if rnd.Intn(2) == 0 {
                        write("\t\tif i%%2 == 0 { acc++ } else { acc-- }\n")
                    }
                    write("\t}\n")
                } else {
                    // while-style
                    k := 3 + rnd.Intn(7)
                    write("\tcount := 0\n")
                    write("\tfor count < %d {\n", k)
                    write("\t\tacc += (count*2 + n)\n")
                    write("\t\tcount++\n")
                    write("\t}\n")
                }
            }

            // Emit if blocks
            for ii := 0; ii < ifs; ii++ {
                write("\tif (acc+j+n)%%%d == 0 {\n", 3+rnd.Intn(5))
                write("\t\tacc += %d\n", 10+rnd.Intn(50))
                write("\t} else if acc%%%d == 1 {\n", 2+rnd.Intn(7))
                write("\t\tacc -= %d\n", 5+rnd.Intn(25))
                write("\t} else {\n")
                write("\t\tacc ^= %d\n", 1+rnd.Intn(1024))
                write("\t}\n")
            }

            // Emit a switch sometimes
            for si := 0; si < switches; si++ {
                mod := 3 + rnd.Intn(4) // 3..6 cases
                write("\tswitch (acc + n)%%%d {\n", mod)
                for c := 0; c < mod-1; c++ {
                    write("\tcase %d:\n", c)
                    write("\t\tacc += %d\n", 1+rnd.Intn(20))
                }
                write("\tdefault:\n")
                write("\t\tacc -= %d\n", 1+rnd.Intn(20))
                write("\t}\n")
            }

            // Extra mixed blocks
            for eb := 0; eb < extra; eb++ {
                switch rnd.Intn(3) {
                case 0:
                    write("\tj = 0\n")
                    write("\tfor ; j < %d; j++ { acc += j }\n", 2+rnd.Intn(6))
                case 1:
                    write("\tif acc > %d { acc = acc/2 }\n", 50+rnd.Intn(200))
                default:
                    write("\tacc += (%d * n)\n", 1+rnd.Intn(10))
                }
            }

            // Return with some variability
            if rnd.Intn(2) == 0 {
                write("\treturn acc + n\n")
            } else {
                write("\tif acc > n { return acc - n }\n")
                write("\treturn n - acc\n")
            }
            write("}\n\n")

            fnIdx++
        }

    default:
        fmt.Fprintf(os.Stderr, "unknown mode: %s\n", *mode)
        os.Exit(2)
    }
}
